                foreach ($candidatePaths as $candidate) {
                    if (file_exists($candidate)) {
                        $resolvedPath = $candidate;
                        break;
                    }
                }

                if (! app()->runningUnitTests() && $resolvedPath) {
                    $existingMedia = $variety->getFirstMedia('slab');
                    if (! $existingMedia || $existingMedia->file_name !== basename($resolvedPath)) {
                        $variety->clearMediaCollection('slab');
                        $variety->addMedia($resolvedPath)
                            ->preservingOriginal()
                            ->withCustomProperties([
                                'alt_text' => $variety->name,
                            ])
                            ->toMediaCollection('slab');
                    }
                }
            }
